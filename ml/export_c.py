#!/usr/bin/env python3
"""Export the trained int8 GRU to C for the firmware.

  python ml/export_c.py            # ml/out/ids_gru.npz -> firmware/include/fw/ids_model.h
                                   #                     + firmware/tests/ids_golden.h

ids_model.h holds the weights as `static const` arrays (flash on an MCU).
ids_golden.h holds a slice of a test recording (raw pump inputs, the features
Python computed, and the int8 model's class probabilities) so the C unit test
can check that firmware/src/ids_rnn.c reproduces the Python model.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import tinygru as G  # noqa: E402
from common import CLASSES, FEATURES, N_FEATURES, FeatureState  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def cf(v: float, digits: int = 9) -> str:
    """A valid C float literal (always has a '.' or exponent)."""
    t = f"{float(v):.{digits}g}"
    if not any(ch in t for ch in ".eninf"):
        t += ".0"
    return t + "f"


def c_floats(a, per_line=8) -> str:
    vals = [cf(v) for v in np.asarray(a).ravel()]
    return ",\n".join("    " + ", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line))


def c_ints(a, per_line=16) -> str:
    vals = [str(int(v)) for v in np.asarray(a).ravel()]
    return ",\n".join("    " + ", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line))


def write_model(z: dict, path: Path) -> int:
    H = int(z["bhn"].shape[0])
    F = int(z["Wi_q"].shape[1])
    C = int(z["Wo_q"].shape[0])
    assert F == N_FEATURES and list(z["features"]) == FEATURES, "feature set changed since training"
    size = G.model_bytes({k: z[k] for k in z})
    enum = "\n".join(f"    IDS_CLASS_{c} = {i}," for i, c in enumerate(CLASSES))
    names = ", ".join(f'"{c}"' for c in CLASSES)
    path.write_text(f"""/*
 * ids_model.h - GENERATED by ml/export_c.py. Do not edit by hand.
 *
 * int8 GRU attack detector: {F} features -> {H} hidden -> {C} classes.
 * Parameter flash: {size['total']} bytes (int8 weights {size['int8_weights']} B,
 * scales {size['scales']} B, float biases {size['float_biases']} B).
 *
 * Weight rows are stacked by gate: [r; z; n]. Each gate block of Wi and Wh,
 * and all of Wo, shares one float scale: w = q * scale.
 */
#ifndef FW_IDS_MODEL_H
#define FW_IDS_MODEL_H

#include <stdint.h>

#define IDS_N_FEATURES  {F}
#define IDS_HIDDEN      {H}
#define IDS_N_CLASSES   {C}
#define IDS_THRESHOLD   {cf(z['threshold'])}  /* alert when P(attack) exceeds this ... */
#define IDS_DEBOUNCE    {int(z['debounce'])}         /* ... for this many consecutive periods */
#define IDS_MODEL_BYTES {size['total']}

typedef enum {{
{enum}
}} ids_class_t;

#define IDS_CLASS_NAMES {{ {names} }}

static const int8_t IDS_WI[3 * IDS_HIDDEN * IDS_N_FEATURES] = {{
{c_ints(z['Wi_q'])}
}};
static const float IDS_WI_SCALE[3] = {{ {", ".join(cf(s) for s in z['Wi_s'])} }};

static const int8_t IDS_WH[3 * IDS_HIDDEN * IDS_HIDDEN] = {{
{c_ints(z['Wh_q'])}
}};
static const float IDS_WH_SCALE[3] = {{ {", ".join(cf(s) for s in z['Wh_s'])} }};

/* [b_r; b_z; b_in] (input and recurrent r/z biases are pre-summed) */
static const float IDS_BI[3 * IDS_HIDDEN] = {{
{c_floats(z['bi'])}
}};
static const float IDS_BHN[IDS_HIDDEN] = {{
{c_floats(z['bhn'])}
}};

static const int8_t IDS_WO[IDS_N_CLASSES * IDS_HIDDEN] = {{
{c_ints(z['Wo_q'])}
}};
static const float IDS_WO_SCALE = {cf(z['Wo_s'][0])};
static const float IDS_BO[IDS_N_CLASSES] = {{
{c_floats(z['bo'])}
}};

#endif /* FW_IDS_MODEL_H */
""", encoding="utf-8", newline="\n")
    return size["total"]


def write_golden(z: dict, telemetry_csv: Path, n: int, path: Path) -> None:
    with open(telemetry_csv, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))[:n]
    fs = FeatureState()
    feats, inputs = [], []
    for r in rows:
        inp = (r["state"] == "RUNNING", r["alarm"] != "NONE", r["alarm"] == "MEM_CORRUPT",
               float(r["target_rate"]), float(r["flow_meas"]), int(r["flow_seq"]), r["flow_ok"] == "1",
               float(r["pressure_meas"]), int(r["pressure_seq"]), r["pressure_ok"] == "1", float(r["duty"]))
        inputs.append(inp)
        feats.append(fs.step(r["state"], r["alarm"], *inp[3:]))
    x = np.array(feats, np.float32)
    probs = G.run_stream(G.dequantize({k: z[k] for k in z}), x)
    lines = []
    for i, (run, al, mem, tgt, fl, fseq, fok, pr, pseq, pok, duty) in enumerate(inputs):
        lines.append(f"    {{ {{ {int(run)}, {int(al)}, {int(mem)}, {cf(tgt)}, {cf(fl)}, {fseq}, {int(fok)}, "
                     f"{cf(pr)}, {pseq}, {int(pok)}, {cf(duty)} }},\n"
                     f"      {{ {', '.join(cf(v, 7) for v in x[i])} }},\n"
                     f"      {{ {', '.join(cf(v, 7) for v in probs[i])} }} }}")
    body = ",\n".join(lines)
    path.write_text(f"""/* GENERATED by ml/export_c.py from {telemetry_csv.name}, rows 0..{len(rows) - 1}:
 * raw pump inputs, the features and int8-model probabilities Python computed. */
#ifndef IDS_GOLDEN_H
#define IDS_GOLDEN_H

#include "fw/ids_rnn.h"

typedef struct {{
    ids_input_t in;
    float       feat[IDS_N_FEATURES];
    float       prob[IDS_N_CLASSES];
}} ids_golden_t;

static const ids_golden_t IDS_GOLDEN[] = {{
{body}
}};
#define IDS_GOLDEN_N {len(rows)}

#endif
""", encoding="utf-8", newline="\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", type=Path, default=ROOT / "ml" / "out" / "ids_gru.npz")
    ap.add_argument("--header", type=Path, default=ROOT / "firmware" / "include" / "fw" / "ids_model.h")
    ap.add_argument("--golden", type=Path, default=ROOT / "firmware" / "tests" / "ids_golden.h")
    ap.add_argument("--golden-from", type=Path, default=None, help="telemetry CSV for golden vectors")
    ap.add_argument("--golden-rows", type=int, default=600, help="max rows in the golden test")
    ap.add_argument("--budget", type=int, default=6144)
    args = ap.parse_args()

    z = dict(np.load(args.model))
    total = write_model(z, args.header)
    print(f"wrote {args.header} ({total} B of parameters, budget {args.budget} B)")
    if total > args.budget:
        sys.exit("model is over the flash budget - retrain with a smaller --hidden")

    src = args.golden_from or sorted((ROOT / "ml" / "data" / "test").glob("*_telemetry.csv"))[0]
    # Run through the first attack (plus its aftermath) so the test exercises it.
    with open(str(src).replace("_telemetry.csv", "_labels.csv"), newline="", encoding="utf-8") as fh:
        lab = list(csv.DictReader(fh))
    first = next((i for i, r in enumerate(lab) if r["attack"] != "NONE"), 0)
    n = min(max(first + 120, 200), args.golden_rows, len(lab))
    write_golden(z, src, n, args.golden)
    print(f"wrote {args.golden} (rows 0..{n - 1} of {src.name}, first attack at row {first})")


if __name__ == "__main__":
    main()
